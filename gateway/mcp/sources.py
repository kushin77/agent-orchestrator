class KbFixtureSource(AuthoritySource):
    """The **declared fake** per-tenant index, labelled fixture-only.

    ``gateway/mcp/kb.py`` documents itself as an in-memory declared graph with no
    real indexer behind it, and ADR-0018 §2 keeps it as the offline fixture
    only. This source is therefore ``fixture_only``: :class:`SourceCatalog`
    refuses it on a production path before any read happens, so a live
    grounding answer can never come from the fake.
    """

    family = "kb-fixture"
    authority = "gateway/mcp/kb.py (declared fake per ADR-0018 §2)"
    operations = ("query", "freshness")
    fixture_only = True

    def __init__(self, root: Any, *, backend: Any = None) -> None:
        super().__init__(root)
        self._backend = backend

    def _backend_or_none(self) -> Optional[Any]:
        if self._backend is not None:
            return self._backend
        try:
            if str(self.root) not in sys.path:
                sys.path.insert(0, str(self.root))
            module = importlib.import_module("gateway.mcp.kb")
            return module.KbRegistry().backend_for("fixture-tenant")
        except Exception:
            return None

    def query(self, *, repo: Optional[str] = None, module_id: Optional[str] = None) -> ReadResult:
        backend = self._backend_or_none()
        if backend is None:
            return ReadResult.no_data(
                "the fixture index backend is not importable in this checkout"
            )
        payload = backend.query(module_id=module_id, repo=repo)
        return ReadResult.ok([
            Fragment(
                family=self.family,
                locator=str(repo or module_id or "fixture"),
                authority=self.authority,
                revision=content_revision(json.dumps(payload, sort_keys=True).encode("utf-8")),
                payload=payload,
            )
        ])

    def freshness(self, *, repo: str) -> ReadResult:
        backend = self._backend_or_none()
        if backend is None:
            return ReadResult.no_data(
                "the fixture index backend is not importable in this checkout"
            )
        payload = backend.freshness(repo)
        return ReadResult.ok([
            Fragment(
                family=self.family,
                locator=str(repo),
                authority=self.authority,
                revision=content_revision(json.dumps(payload, sort_keys=True).encode("utf-8")),
                payload=payload,
            )
        ])


class FleetSource(AuthoritySource):
    """The ``ao.bridge/v1`` manifest + per-family revisions (a change signal).

    One fragment per bridge family, whose ``revision`` is the bridge's own
    content digest of that family's source - the citation form the ticket asks
    for ("bridge family + revision"). The push channel is a signal, not a data
    channel, so this family carries revisions and the manifest rows, and never a
    payload copy of another family.
    """

    family = "fleet"
    authority = BRIDGE_CONTRACT
    operations = ("snapshot",)

    def __init__(self, root: Any, *, bridge: Any = None) -> None:
        super().__init__(root)
        self._bridge = bridge
        self.fixture_only = bool(getattr(bridge, "fixture_only", False)) if bridge else False

    def snapshot(self) -> ReadResult:
        try:
            if self._bridge is not None:
                bridge = self._bridge
            else:
                if str(self.root) not in sys.path:
                    sys.path.insert(0, str(self.root))
                bridge = importlib.import_module("portal.server.bridge").LiveBridge(
                    repo_root=self.root
                )
            manifest = bridge.manifest()
            revisions = bridge.revisions()
        except Exception as exc:
            return ReadResult.no_data(
                f"the {BRIDGE_CONTRACT} manifest is unavailable from this "
                f"checkout: {exc}"
            )
        rows = manifest.get("families") if isinstance(manifest, Mapping) else None
        if not isinstance(rows, list) or not rows:
            return ReadResult.no_data(
                f"the {BRIDGE_CONTRACT} manifest declares no family rows"
            )
        fragments = []
        for row in rows:
            if not isinstance(row, Mapping):
                continue
            family_id = str(row.get("id", ""))
            fragments.append(
                Fragment(
                    family=self.family,
                    locator=family_id,
                    authority=BRIDGE_CONTRACT,
                    revision=str(revisions.get(family_id, "")),
                    payload={
                        "id": family_id,
                        "source": row.get("source"),
                        "path": row.get("path"),
                        "kind": row.get("kind"),
                        "contract": manifest.get("contract"),
                    },
                )
            )
        fragments.sort(key=lambda fragment: fragment.locator)
        if not fragments:
            return ReadResult.no_data(
                f"the {BRIDGE_CONTRACT} manifest declares no readable family row"
            )
        return ReadResult.ok(fragments)


# --------------------------------------------------------------------------- #
# the catalogue: the single gate every family read passes through
# --------------------------------------------------------------------------- #
@dataclass
class SourceCatalog:
    """The declared read-only families, read through one fail-closed gate.

    The catalogue - not the caller - decides what may be read: an unknown family
    and a ``fixture_only`` family on a production path both yield ``NO_DATA``
    with a reason, so a tool can never widen its own scope by asking.
    """

    root: Any
    mode: str = MODE_PRODUCTION
    _sources: Dict[str, AuthoritySource] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.mode not in MODES:
            raise ValueError(f"unknown catalogue mode {self.mode!r}")

    # -- construction ---------------------------------------------------- #
    @classmethod
    def from_repo_root(
        cls,
        root: Any,
        *,
        mode: str = MODE_PRODUCTION,
        bridge: Any = None,
    ) -> "SourceCatalog":
        """The declared catalogue over ``root``.

        ``bridge`` is the ``ao.bridge/v1`` read surface the ``registry`` and
        ``fleet`` families consume. It defaults to the real
        ``portal.server.bridge.LiveBridge`` over ``root``; injecting a fixture
        bridge is how an offline test exercises those families - and because a
        fixture bridge is labelled ``fixture_only``, the catalogue refuses it on
        a production path regardless of who supplied it.
        """
        catalog = cls(root=root, mode=mode)
        catalog.add(BoardSource(root))
        catalog.add(BudgetSource(root))
        catalog.add(LedgerSource(root))
        catalog.add(RegistrySource(root, bridge=bridge))
        catalog.add(KnowledgeSource(root))
        catalog.add(CodeIndexSource(root))
        catalog.add(FleetSource(root, bridge=bridge))
        return catalog

    def add(self, source: AuthoritySource) -> "SourceCatalog":
        if source.family in self._sources:
            raise ValueError(f"duplicate source for family {source.family!r}")
        self._sources[source.family] = source
        return self

    # -- read surface ----------------------------------------------------- #
    def families(self) -> Tuple[str, ...]:
        return tuple(sorted(self._sources))

    def source(self, family: str) -> AuthoritySource:
        return self._sources[family]

    def is_fixture_only(self, family: str) -> bool:
        return bool(self._sources[family].fixture_only)

    def call(self, family: str, operation: str, **kwargs: Any) -> ReadResult:
        """Read one operation of one family (fail closed, never a fallback)."""
        source = self._sources.get(family)
        if source is None:
            return ReadResult.no_data(
                f"no read-only source is declared for family {family!r} "
                f"(declared families: {', '.join(self.families())})"
            )
        if source.fixture_only and self.mode == MODE_PRODUCTION:
            return ReadResult.no_data(FIXTURE_REFUSAL % family)
        try:
            return source.perform(operation, **kwargs)
        except SourceUnavailable as exc:
            return ReadResult.no_data(str(exc))


