"""Read-only authority readers behind the enterprise (chat) tool family.

Issue kushin77/agent-orchestrator#504 (EPIC #500, "Chat grounding: the
read-only enterprise tool family + the citations envelope").

Every reader here **consumes an existing authority and returns it verbatim**,
stamped with that authority's own revision. Nothing in this module re-derives a
projection: ADR-0012 froze "a second projection is a second engine", and
ADR-0018 §3 froze "a shape that exists in a published contract is consumed,
never mirrored". So this module owns *no* state, writes *no* file, and asserts
*nothing* of its own about the facts it reads - it is a citation producer.

The authorities, one per family (all read on every call, so an edit on disk is
observed without a restart - the ``ao.bridge/v1`` property):

===============  ============================================================
family           authority
===============  ============================================================
``board``        ``.board/snapshot.json`` - the ticket join node (ADR-0014)
``budget``       ``telemetry/budgets/config/policies.yaml`` - declared policy
``ledger``       ``telemetry/ledger`` - consumed via ``telemetry.ledger.store``
``registry``     ``ao.bridge/v1`` ``registry`` family (``registry/profiles``)
``knowledge``    ``governance/knowledge/catalog.json`` - the real, in-repo
                 institutional-knowledge index (generated by its own indexer)
``codeidx``      ``kushin77/code-indexing`` - the real code-symbol index, which
                 is **not reachable from this repo**; declared here so the tool
                 says so instead of inventing an answer
``fleet``        ``ao.bridge/v1`` manifest + per-family revisions
``kb-fixture``   ``gateway/mcp/kb.py`` - the **declared fake** (ADR-0018 §2),
                 labelled ``fixture_only`` and refused on a production path
===============  ============================================================

**Honesty (AO-GR-19).** An absent or empty authority is never an empty
success: :class:`ReadResult` refuses to be constructed in the ``NO_DATA`` state
without a reason naming what was missing, and a ``fixture_only`` source is
refused by :class:`SourceCatalog` itself when the catalogue runs in production
mode - so a production grounding path cannot reach the declared fake index even
by mistake.
"""

